export const getFriendshipMilestone = (streakDays: number): FriendshipMilestone | undefined => {
  if (streakDays >= 100) {
    return {
      days: 100,
      title: 'Century of Connection',
      badge: '👑',
      tier: 'diamond',
      description: '100-day legendary streak of unbroken connection.',
    };
  }
  if (streakDays >= 50) {
    return {
      days: 50,
      title: 'Golden Friendship',
      badge: '⭐',
      tier: 'gold',
      description: '50-day golden milestone of shared closeness.',
    };
  }
  if (streakDays >= 30) {
    return {
      days: 30,
      title: 'Monthly Bond',
      badge: '💫',
      tier: 'silver',
      description: '30-day milestone of daily conversations and warmth.',
    };
  }
  if (streakDays >= 7) {
    return {
      days: 7,
      title: 'Week of Warmth',
      badge: '🌱',
      tier: 'bronze',
      description: '7-day milestone of blossoming connection.',
    };
  }
  return undefined;
};

